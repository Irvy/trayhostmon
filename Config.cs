using System;
using System.Collections.Generic;
using System.Drawing;
using System.IO;
using System.Text;

namespace PingMon
{
    public class HostConfig
    {
        public string Address;
        public int IntervalSec;
        public int TimeoutMs;
        public int Threshold;
        public int Buffer = 32; // Ping payload size in bytes
    }

    // Running values. Hosts are stored as normalized strings, prefaced with '-' if disabled.
    public class AppConfig
    {
        public int IntervalSec = 5;
        public int TimeoutMs = 1000;
        public int Threshold = 3;
        public int Buffer = 32;
        public List<string> Hosts = new List<string>();
        public Point? WidgetPos;
        // Host lines from the file that were ignored when loading.
        public List<string> Skipped = new List<string>();
    }

    public static class Config
    {
        public static readonly string IniPath =
            Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "pingmon.ini");

        private const string Header =
            "; Generated by pingmon. Edits are overwritten on the next write.";
        private const string SettingsHint =
            "; Changed a value by hand? Use 'Reload config' in the tray menu.";

        // Creates the file with defaults if it doesn't exist.
        public static void EnsureExists()
        {
            if (!File.Exists(IniPath))
                Save(IniPath, new AppConfig());
        }

        // Writes the whole file from the running values. Uses a temp file and swaps it in.
        public static void Save(string path, AppConfig cfg)
        {
            var sb = new StringBuilder();
            sb.Append(Header).Append("\r\n");
            sb.Append(SettingsHint).Append("\r\n");
            sb.Append("[settings]\r\n");
            sb.Append("interval=").Append(cfg.IntervalSec).Append("\r\n");
            sb.Append("timeout=").Append(cfg.TimeoutMs).Append("\r\n");
            sb.Append("threshold=").Append(cfg.Threshold).Append("\r\n");
            sb.Append("buffer=").Append(cfg.Buffer).Append("\r\n");
            sb.Append("\r\n");
            sb.Append("[hosts]\r\n");
            foreach (string h in cfg.Hosts) sb.Append(h).Append("\r\n");
            if (cfg.WidgetPos.HasValue)
            {
                sb.Append("\r\n");
                sb.Append("[widget]\r\n");
                sb.Append("x=").Append(cfg.WidgetPos.Value.X).Append("\r\n");
                sb.Append("y=").Append(cfg.WidgetPos.Value.Y).Append("\r\n");
            }

            string tmp = path + ".tmp";
            File.WriteAllText(tmp, sb.ToString(), new UTF8Encoding(false));
            if (File.Exists(path)) File.Replace(tmp, path, null);
            else File.Move(tmp, path);
        }

        // Single check for IP or hostname input. Returns the normalized form, or false if invalid.
        // Used by config loading and by the Add host dialog.
        public static bool TryNormalizeHost(string input, out string host)
        {
            host = null;
            if (string.IsNullOrEmpty(input)) return false;
            string s = input.Trim().ToLowerInvariant();
            if (s.Length == 0) return false;

            // Digits and dots only: must be a complete IPv4 address.
            bool numeric = true;
            foreach (char c in s)
                if (!(char.IsDigit(c) || c == '.')) { numeric = false; break; }
            if (numeric)
            {
                string[] parts = s.Split('.');
                if (parts.Length != 4) return false;
                foreach (string p in parts)
                {
                    int n;
                    if (p.Length == 0 || p.Length > 3 || !int.TryParse(p, out n) || n > 255) return false;
                }
                host = s;
                return true;
            }

            // Hostname: dot-separated labels of letters, digits, hyphens and underscores.
            if (s.Length > 253) return false;
            foreach (string label in s.Split('.'))
            {
                if (label.Length == 0 || label.Length > 63) return false;
                if (label[0] == '-' || label[label.Length - 1] == '-') return false;
                foreach (char c in label)
                {
                    bool ok = (c < 128 && char.IsLetterOrDigit(c)) || c == '-' || c == '_';
                    if (!ok) return false;
                }
            }
            host = s;
            return true;
        }

        // Reads the file into running values. Tolerates inline comments and unknown lines.
        // Invalid or duplicate host lines are reported in Skipped.
        // Hosts prefaced with '-' are disabled.
        public static AppConfig Load(string path)
        {
            var cfg = new AppConfig();
            var settings = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            string section = null;
            int wx = 0, wy = 0;
            bool hasX = false, hasY = false;

            foreach (string raw in File.ReadAllLines(path))
            {
                string line = StripComment(raw);
                if (line.Length == 0) continue;

                if (line[0] == '[' && line[line.Length - 1] == ']')
                {
                    section = line.Substring(1, line.Length - 2).Trim().ToLowerInvariant();
                    continue;
                }

                if (section == "settings")
                {
                    int eq = line.IndexOf('=');
                    if (eq > 0) settings[line.Substring(0, eq).Trim()] = line.Substring(eq + 1).Trim();
                }
                else if (section == "hosts")
                {
                    // Check for disabled prefix
                    string lineToCheck = line;
                    bool disabled = false;
                    if (line.StartsWith("-"))
                    {
                        lineToCheck = line.Substring(1);
                        disabled = true;
                    }

                    string host;
                    if (!TryNormalizeHost(lineToCheck, out host) || !seen.Add(host))
                        cfg.Skipped.Add(line);
                    else
                        cfg.Hosts.Add(disabled ? "-" + host : host);
                }
                else if (section == "widget")
                {
                    int eq = line.IndexOf('=');
                    if (eq <= 0) continue;
                    string key = line.Substring(0, eq).Trim().ToLowerInvariant();
                    int n;
                    if (!int.TryParse(line.Substring(eq + 1).Trim(), out n)) continue;
                    if (key == "x" && !hasX) { wx = n; hasX = true; }
                    else if (key == "y" && !hasY) { wy = n; hasY = true; }
                }
            }

            if (hasX && hasY) cfg.WidgetPos = new Point(wx, wy);
            cfg.IntervalSec = Clamp(Get(settings, "interval", 5), 1, 3600);
            cfg.TimeoutMs = Clamp(Get(settings, "timeout", 1000), 500, 10000);
            cfg.Threshold = Clamp(Get(settings, "threshold", 3), 1, 100);
            cfg.Buffer = Clamp(Get(settings, "buffer", 32), 0, 65500);
            return cfg;
        }

        // Builds a HostConfig for one address using the running settings.
        // hostSpec may be prefixed with '-' for disabled hosts (only used for address lookup).
        public static HostConfig ToHostConfig(AppConfig cfg, string addressSpec)
        {
            // Strip the disabled prefix if present
            string address = addressSpec.StartsWith("-") ? addressSpec.Substring(1) : addressSpec;
            return new HostConfig
            {
                Address = address,
                IntervalSec = cfg.IntervalSec,
                TimeoutMs = cfg.TimeoutMs,
                Threshold = cfg.Threshold,
                Buffer = cfg.Buffer
            };
        }

        // Extracts just the address from a host specification (with optional '-' prefix)
        public static string GetAddress(string hostSpec)
        {
            return hostSpec.StartsWith("-") ? hostSpec.Substring(1) : hostSpec;
        }

        // Checks if a host specification is marked as disabled
        public static bool IsDisabled(string hostSpec)
        {
            return hostSpec.StartsWith("-");
        }

        // Creates a host specification with the enabled/disabled flag
        public static string MakeHostSpec(string address, bool enabled)
        {
            return enabled ? address : "-" + address;
        }

        private static string StripComment(string raw)
        {
            int semi = raw.IndexOf(';');
            string line = semi >= 0 ? raw.Substring(0, semi) : raw;
            return line.Trim();
        }

        private static int Get(Dictionary<string, string> settings, string key, int fallback)
        {
            string v;
            int n;
            if (settings.TryGetValue(key, out v) && int.TryParse(v, out n)) return n;
            return fallback;
        }

        private static int Clamp(int v, int min, int max)
        {
            return v < min ? min : (v > max ? max : v);
        }
    }
}
